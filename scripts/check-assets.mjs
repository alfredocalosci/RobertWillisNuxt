#!/usr/bin/env node
/**
 * Pre-build checks for content/library/*.yml (runs as the pregenerate hook):
 * - every visible publication's cover exists in public/Library/img/ (exit 1 if not);
 * - every visible publication with a PDF has an `archiveId` (exit 1 if not): the PDFs are
 *   served from the Internet Archive, not from this site;
 * - writes the Apache 301s for the old /Library/pdf/<file> URLs into public/.htaccess.
 */
import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs'
import { join, resolve } from 'node:path'

const ROOT = resolve(import.meta.dirname, '..')
const DIR = join(ROOT, 'content/library')
const HTACCESS = join(ROOT, 'public/.htaccess')
const field = (yml, k) => {
  const m = yml.match(new RegExp(`^${k}: (.*)$`, 'm'))
  return !m || m[1] === 'null' ? null : JSON.parse(m[1])
}

const missingCovers = [], missingArchive = [], redirects = []
let visible = 0
for (const f of readdirSync(DIR).filter(f => f.endsWith('.yml')).sort()) {
  const yml = readFileSync(join(DIR, f), 'utf8')
  if (field(yml, 'hidden') === true) continue
  visible++
  const cover = field(yml, 'cover'), file = field(yml, 'file'), archiveId = field(yml, 'archiveId')
  if (cover && !existsSync(join(ROOT, 'public/Library/img', cover))) missingCovers.push(cover)
  if (file && !archiveId) missingArchive.push(f)
  if (file && archiveId)
    redirects.push(`Redirect 301 "/Library/pdf/${file}" "https://archive.org/download/${archiveId}/${encodeURIComponent(file)}"`)
}

// Keep the generated block in .htaccess in sync with the YAML.
const BEGIN = '# BEGIN library-pdf-redirects (generated by scripts/check-assets.mjs, do not edit)'
const END = '# END library-pdf-redirects'
const block = [BEGIN, '<IfModule mod_alias.c>', ...redirects.map(r => `  ${r}`), '</IfModule>', END].join('\n')
const ht = readFileSync(HTACCESS, 'utf8')
const next = ht.includes(BEGIN)
  ? ht.replace(new RegExp(`${BEGIN.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}[\\s\\S]*?${END}`), block)
  : `${ht.trimEnd()}\n\n# Old PDF links (2016 site) → Internet Archive\n${block}\n`
if (next !== ht) writeFileSync(HTACCESS, next)

console.log(`[check-assets] ${visible} visible publications, ${redirects.length} PDF redirects in .htaccess`)
let fail = false
if (missingArchive.length) {
  console.error(`[check-assets] ✖ PDF without archiveId (no download link):\n  ${missingArchive.join('\n  ')}`)
  fail = true
}
if (missingCovers.length) {
  console.error(`[check-assets] ✖ missing covers:\n  ${missingCovers.join('\n  ')}`)
  fail = true
}
if (fail) process.exit(1)
console.log('[check-assets] all covers present, all PDFs on the Internet Archive')
